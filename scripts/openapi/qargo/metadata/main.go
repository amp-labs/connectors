package main

import (
	"github.com/amp-labs/connectors/common"
	"github.com/amp-labs/connectors/internal/goutils"
	"github.com/amp-labs/connectors/scripts/openapi/internal/api"
	"github.com/amp-labs/connectors/scripts/openapi/internal/api/filters"
	mapping "github.com/amp-labs/connectors/scripts/openapi/internal/api/map"
	"github.com/amp-labs/connectors/scripts/openapi/internal/api/map/mappingfields"
	"github.com/amp-labs/connectors/scripts/openapi/internal/api/output"
	"github.com/amp-labs/connectors/scripts/openapi/internal/api/pipeline"
	"github.com/amp-labs/connectors/scripts/openapi/internal/api/reducers"
	"github.com/amp-labs/connectors/scripts/openapi/internal/api/spec"
	"github.com/amp-labs/connectors/scripts/openapi/qargo/internal/files"
	"github.com/getkin/kin-openapi/openapi3"
)

func main() {
	extractor, err := files.OpenApiFile.Extractor()
	goutils.MustBeNil(err)

	// Paginated lists return {"items": [...], "next_cursor": ...}.
	// https://api-docs.qargo.com/docs/section/api-best-practices/pagination
	getSchemas, err := extractor.ExtractListSchemas(api.GET,
		api.List.WithArrayLocator(func(_, fieldName string) bool {
			return fieldName == "items"
		}),
	)
	goutils.MustBeNil(err)

	// Only the collections this connector reads.
	readObjects := filters.NewRules(
		"/v1/companies/company",
	)

	pipe := pipeline.NewSchemaPipe(getSchemas).
		Filter(filters.KeepWithPath(filters.AndPathMatcher{
			filters.NoIdPath{}, filters.NewAllowPathStrategy(readObjects),
		})).
		Reduce(reducers.ShortestNameFromUrlWithFullFallback).
		Map(mapping.DisplayNameFromObjectName).
		Map(mapping.DisplayNameFormat(
			mapping.CamelCaseToSpaceSeparated,
			mapping.CapitalizeFirstLetterEveryWord,
		)).
		Map(mapping.Fields(
			nullableField,
			numberField,
			dateField,
			mappingfields.DisplayNameFormat(func(_, name string) string {
				return mapping.CapitalizeFirstLetterEveryWord(mapping.CamelCaseToSpaceSeparated(name))
			}),
		))

	output.PrintUnusedRules("readObjects", readObjects)
	goutils.MustBeNil(output.WriteMetadata(files.OutputDir, pipe))
	goutils.MustBeNil(output.WriteQueryParamStats(files.OutputDir, pipe))
	goutils.MustBeNil(output.WriteEndpoints(files.OutputDir, &pipe, nil, nil, nil))
}

// nullableField types an optional property by its non-null option. The spec (OpenAPI 3.1,
// generated by FastAPI) writes optional fields as anyOf [X, null], which the extractor leaves untyped.
func nullableField(field spec.Field) spec.Field {
	option := nonNullOption(property(field))
	if option == nil {
		return field
	}

	if option.Type != nil && len(*option.Type) != 0 {
		field.Type = (*option.Type)[0]
	}

	for _, value := range option.Enum {
		if text, ok := value.(string); ok {
			field.ValueOptions = append(field.ValueOptions, text)
		}
	}

	return field
}

// numberField types JSON numbers as float; the spec does not tell integers from decimals here.
func numberField(field spec.Field) spec.Field {
	if field.Type == openapi3.TypeNumber {
		field.ValueType = common.ValueTypeFloat
	}

	return field
}

// dateField marks ISO 8601 dates and datetimes (always UTC).
// https://api-docs.qargo.com/docs/section/api-best-practices/date-and-time-formats
func dateField(field spec.Field) spec.Field {
	schema := property(field)
	if option := nonNullOption(schema); option != nil {
		schema = option
	}

	if schema == nil {
		return field
	}

	switch schema.Format {
	case "date-time":
		field.ValueType = common.ValueTypeDateTime
	case "date":
		field.ValueType = common.ValueTypeDate
	}

	return field
}

func property(field spec.Field) *openapi3.Schema {
	if field.Origin.Schema == nil {
		return nil
	}

	ref, ok := field.Origin.Schema.Properties[field.Name]
	if !ok || ref.Value == nil {
		return nil
	}

	return ref.Value
}

// nonNullOption returns X of anyOf [X, null], or nil when the schema has another shape.
func nonNullOption(schema *openapi3.Schema) *openapi3.Schema {
	if schema == nil || len(schema.AnyOf) != 2 { // nolint:mnd
		return nil
	}

	var option *openapi3.Schema

	for _, ref := range schema.AnyOf {
		if ref.Value == nil {
			return nil
		}

		if ref.Value.Type != nil && ref.Value.Type.Is(openapi3.TypeNull) {
			continue
		}

		option = ref.Value
	}

	return option
}
